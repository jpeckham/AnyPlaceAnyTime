"""Build a reviewable placement allowlist from the target installation; never copy profiles."""
import argparse,json
from pathlib import Path

parser=argparse.ArgumentParser()
parser.add_argument('--database',required=True,help='SPT_Runtime/SPT_Data/database')
parser.add_argument('--output',default=str(Path(__file__).resolve().parents[1]/'src/PlacementCatalog.cs'))
args=parser.parse_args()
root=Path(args.database)
def read(path): return json.loads((root/path).read_text(encoding='utf-8-sig'))
items=read('templates/items.json');quests=read('templates/quests.json');locale=read('locales/global/en.json')
targets={}
def walk(value):
    if isinstance(value,dict):
        kind=value.get('conditionType')
        if kind in ('LeaveItemAtLocation','PlaceBeacon'):
            for template in value.get('target',[]): targets.setdefault(template,set()).add(kind)
        for child in value.values(): walk(child)
    elif isinstance(value,list):
        for child in value: walk(child)
walk(quests)
original={'5991b51486f77447b112d44f','5b4391a586f7745321235ab2','5ac78a9b86f7741cca0bbd8d'}
normal=[];excluded=[]
for template,kinds in sorted(targets.items()):
    definition=items.get(template)
    if not definition: raise ValueError('Missing placement template '+template)
    if definition['_props'].get('QuestItem') is not False:
        excluded.append(template);continue
    name=locale.get(template+' Name',definition['_name'])
    normal.append(f'        new({json.dumps(template)}, {json.dumps(name,ensure_ascii=True)}, {str("PlaceBeacon" in kinds or template in original).lower()}),')
text='''// Generated by tools/generate_catalog.py from local EFT 1.3.0.0.48484 quest/item data.
namespace AnyPlaceAnyTime;
internal sealed record PlacementTemplate(string Id,string Name,bool NeedsPrefab);
internal static class PlacementCatalog
{
    internal static readonly PlacementTemplate[] Entries = [
'''+ '\n'.join(normal)+'''
    ];
    internal static readonly Dictionary<string,PlacementTemplate> ById = Entries.ToDictionary(entry=>entry.Id);
    internal static readonly string[] ExcludedTaskItemIds = [
'''+ '\n'.join('        '+json.dumps(t)+',' for t in excluded)+'''
    ];
}
'''
Path(args.output).write_text(text,encoding='utf-8',newline='\n')
print(f'Generated {len(normal)} ordinary placement templates; excluded {len(excluded)} task-storage templates')
